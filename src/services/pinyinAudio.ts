export interface PinyinAudioOptions {
  pinyin: string
  tone?: 0 | 1 | 2 | 3 | 4
}

export function audioFileExists(pinyin: string, tone: number = 0): boolean {
  const fileName = tone === 0 ? `${pinyin}.mp3` : `${pinyin}${tone}.mp3`
  return AUDIO_FILE_LIST.has(fileName)
}

export function getPinyinAudioFileID(options: PinyinAudioOptions): string | null {
  const { pinyin, tone = 0 } = options
  
  if (!audioFileExists(pinyin, tone)) {
    console.warn(`Audio file not found: ${pinyin}${tone === 0 ? '' : tone}.mp3`)
    return null
  }
  
  if (tone === 0) {
    return `${CLOUD_BASE_URL}${pinyin}.mp3`
  }
  
  return `${CLOUD_BASE_URL}${pinyin}${tone}.mp3`
}

export function getPinyinAudioFileIDs(pinyinList: string[], tone?: 0 | 1 | 2 | 3 | 4): (string | null)[] {
  return pinyinList.map(pinyin => getPinyinAudioFileID({ pinyin, tone }))
}

export function getPinyinAllTonesFileIDs(pinyin: string): (string | null)[] {
  const fileIDs: (string | null)[] = []
  
  fileIDs.push(getPinyinAudioFileID({ pinyin, tone: 0 }))
  
  for (let tone = 1; tone <= 4; tone++) {
    fileIDs.push(getPinyinAudioFileID({ pinyin, tone: tone as 1 | 2 | 3 | 4 }))
  }
  
  return fileIDs
}

export function getPinyinBatchFileIDs(pinyinTonePairs: Array<{ pinyin: string; tone?: 0 | 1 | 2 | 3 | 4 }>): (string | null)[] {
  return pinyinTonePairs.map(pair => getPinyinAudioFileID(pair))
}
