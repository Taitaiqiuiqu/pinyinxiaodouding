export interface PinyinWithTone {
  pinyin: string
  tone: 0 | 1 | 2 | 3 | 4
}

export function parsePinyinWithTone(pinyin: string): PinyinWithTone {
  let plainPinyin = ''
  let tone: 0 | 1 | 2 | 3 | 4 = 0
  
  for (const char of pinyin) {
    if (TONE_MAP[char]) {
      plainPinyin += TONE_MAP[char].plain
      if (TONE_MAP[char].tone !== 0) {
        tone = TONE_MAP[char].tone
      }
    } else {
      plainPinyin += char
    }
  }
  
  return { pinyin: plainPinyin, tone }
}

export function parseWordPinyin(wordPinyin: string): PinyinWithTone[] {
  const parts = wordPinyin.trim().split(/\s+/)
  return parts.map(part => parsePinyinWithTone(part))
}

